'use strict';
const fs=require('fs'),path=require('path'),vm=require('vm'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),read=f=>fs.readFileSync(path.join(root,f),'utf8');
const events=[];
const win={scrollY:0,pageYOffset:0,location:{hash:'#/category/library'},addEventListener:(n,cb)=>{win.events[n]=cb},events:{},scrollTo:({top})=>{events.push(['scroll',top]);win.scrollY=top;}};
const history={scrollRestoration:'auto',pushState:(_state,_title,hash)=>{win.location.hash=hash;},replaceState:(_state,_title,hash)=>{win.location.hash=hash;},back:()=>events.push(['back'])};
const localStorage={getItem:()=>null,setItem:()=>{}};
const context=vm.createContext({window:win,history,localStorage,Date,URL,console,requestAnimationFrame:cb=>cb()});
vm.runInContext(read('src/script.js'),context);
const app=vm.runInContext('urbanForager()',context);
app.$nextTick=cb=>cb(); app.rememberRecent=()=>{};app.hydrateMissingSpeciesPhotos=()=>{};
app.initializeRouting();
assert.equal(app.screen,'library');assert.equal(history.scrollRestoration,'manual');
const plant=app.plants[0];
win.scrollY=1374;
app.openPlant(plant);
assert.equal(app.browseReturn.screen,'library');
assert.equal(app.browseReturn.scrollY,1374);
assert.equal(app.screen,'details');
assert.equal(win.scrollY,0);
const n=events.length;
win.location.hash='#/category/library';
app.routeListener();
assert.equal(app.screen,'library');
assert.equal(win.scrollY,1374,'browser Back should restore pre-dossier position');
assert.deepEqual(JSON.stringify(events.slice(n)),JSON.stringify([['scroll',1374]]));
win.scrollY=923; app.screen='favorites';win.location.hash='#/category/favorites';app.openPlant(plant);
win.location.hash='#/category/favorites';app.routeListener();
assert.equal(win.scrollY,923,'Favorites must restore independently');
win.scrollY=1811;app.screen='recent';win.location.hash='#/category/recent';app.openPlant(plant);
win.location.hash='#/category/recent';app.routeListener();
assert.equal(win.scrollY,1811,'Recent must restore independently');
app.openPlant(plant);
app.returnToResults();
assert.equal(events.at(-1)[0],'back','Results uses browser Back for a dossier hash');
app.navigate('home');
assert.equal(win.scrollY,0,'normal navigation to Home begins at top');
const resources=JSON.parse(read('src/script.js').match(/window\.urbanForagerResourceData = (\[.*?\]);\s*window\.urbanForagerOpenResourceVideo/s)[1]);
for(const name of ['Ethnobotany: Plants Sustaining People','Weaving and Dyeing Materials','Native Knowledge 360°','Plants of the World Online','FoodData Central Data Types'])assert(resources.some(x=>x.title===name));
const html=read('index.html');
assert.equal((html.match(/data-resource-card/g)||[]).length,resources.length,'resource catalog and pre-rendered cards must match');
assert(!html.includes('Photo Health Check</strong>'),'consumer navigation should not have the diagnostic link');
assert(!read('sw.js').includes('PHOTO-HEALTH-CHECK'),'SW should not pre-cache developer utility');
assert(read('manifest.json').includes('ethnobotany'));
assert.equal(read('dist/script.js'),read('src/script.js'));
assert.equal(JSON.parse(read('urbanforager-kodeWeave.json')).html,html);
console.log('PASS 2T: browser-style Back, Results, favorites, recent, normal navigation, resources, minimal runtime, source sync.');
