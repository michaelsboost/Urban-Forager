// Dependency-free regression checks for the dossier print renderer.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const code = fs.readFileSync(path.join(__dirname, '../src/script.js'), 'utf8');
const context = vm.createContext({ window: {}, console, URL, Date });
vm.runInContext(code, context);
const plants = context.window.URBAN_FORAGER_PLANTS;
const full = vm.runInContext('ufBuildPrintDocument(window.URBAN_FORAGER_PLANTS,UF_PRINT_SECTIONS.map(s=>s.id),"compact")',context);
assert.equal((full.match(/data-print-plant-id=/g) || []).length, plants.length);
assert.ok(plants.length >= 95);
assert.match(full,/Indigenous uses/);
assert.match(full,/Sources &amp; verification/);
assert.match(full,/https:\/\//);
assert.match(full,/Identification warning/);
assert.match(full,/uf-paper-compact/);
const nutrition = vm.runInContext('ufBuildPrintDocument([window.URBAN_FORAGER_PLANTS[0]],["nutrition"],"compact")',context);
assert.match(nutrition,/<h3>Nutrition<\/h3>/);
assert.doesNotMatch(nutrition,/<h3>Indigenous uses<\/h3>/);
assert.match(nutrition,/USDA FDC 2709588/);
assert.match(nutrition,/Sources supporting selected sections/);
const escaped = vm.runInContext('ufBuildPrintDocument([{id:500,commonName:"<script>alert(1)</script>",sources:[]}],["identification"],"compact")',context);
assert.doesNotMatch(escaped,/<script>/);
const app = vm.runInContext('urbanForager()',context);
assert.equal(app.printScope,'all');
assert.equal(app.printLayout,'compact');
assert.equal(app.printSections.length,11);
app.printScope='selected';app.printSelectedIds=[1,3];
assert.equal(app.printPlants.length,2);
app.printScope='favorites';app.favoriteIds=[1,4,6];
assert.equal(app.printPlants.length,3);
app.printScope='filtered';app.query='dandelion';
assert.ok(app.printPlants.length>0);
console.log(`Pass: ${plants.length} printable dossiers, all scopes/defaults, selective sections, citations, escaping.`);
